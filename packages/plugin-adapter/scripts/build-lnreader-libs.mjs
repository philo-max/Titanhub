import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const entry = `
import * as cheerio from 'cheerio/slim';
import * as htmlparser2 from 'htmlparser2';
import dayjs from 'dayjs';
globalThis.__lnrLibs = { cheerio, htmlparser2, dayjs };
`;

const result = await build({
  stdin: { contents: entry, resolveDir: root, sourcefile: 'lnreader-libs-entry.js' },
  bundle: true,
  write: false,
  format: 'iife',
  platform: 'neutral',
  mainFields: ['module', 'main'],
  conditions: ['browser', 'import', 'module'],
  target: 'es2020',
  minify: true,
  legalComments: 'none',
});

const code = result.outputFiles[0].text;
const output = `// Generated by scripts/build-lnreader-libs.mjs. Do not edit.\nexport const LNREADER_LIBS = ${JSON.stringify(code)};\n`;
fs.writeFileSync(path.join(root, 'lnreader-libs.generated.ts'), output);
console.log(`lnreader-libs.generated.ts: ${(code.length / 1024).toFixed(0)} KiB`);
